import yfinance as yf
import numpy as np
import pandas as pd
import matplotlib.pyplot as plt
import torch
import torch.nn as nn
import torch.optim as optim
import time

from sklearn.preprocessing import MinMaxScaler
from sklearn.metrics import mean_absolute_error, mean_squared_error
from torch.utils.data import TensorDataset, DataLoader

device = torch.device("cuda" if torch.cuda.is_available() else "cpu")
print("Device:", device)

ticker = "TCS.NS"

data = yf.download(
    ticker,
    period="5y",
    interval="1d",
    auto_adjust=True,
    progress=False
)

# Handle Yahoo Finance MultiIndex columns
if isinstance(data.columns, pd.MultiIndex):
    data.columns = data.columns.get_level_values(0)

data = data[["Open", "High", "Low", "Close", "Volume"]]
data = data.dropna()

print(data.head())
print("\nTotal records:", len(data))

plt.figure(figsize=(12, 5))

plt.plot(data.index, data["Close"], label="Closing Price")

plt.title("TCS Stock Closing Price")
plt.xlabel("Date")
plt.ylabel("Price (INR)")
plt.legend()
plt.grid()
plt.show()


# Visualize OHLCV features
data[["Open", "High", "Low", "Close", "Volume"]].plot(
    subplots=True,
    figsize=(12, 10),
    title="Stock Market Features"
)

plt.tight_layout()
plt.show()

# Convert data into NumPy array
values = data.values.astype("float32")

# Chronological split
split_index = int(len(values) * 0.8)

# Min-Max scaling
scaler = MinMaxScaler()

train_scaled = scaler.fit_transform(values[:split_index])
all_scaled = scaler.transform(values)

# Create sliding windows
sequence_length = 30
X_train, y_train = [], []
X_val, y_val = [], []

# Training sequences
for i in range(sequence_length, split_index):
    X_train.append(all_scaled[i-sequence_length:i])
    y_train.append(all_scaled[i, 3])  # Closing price

# Validation sequences
for i in range(split_index, len(all_scaled)):
    X_val.append(all_scaled[i-sequence_length:i])
    y_val.append(all_scaled[i, 3])

X_train = torch.tensor(np.array(X_train), dtype=torch.float32)
y_train = torch.tensor(np.array(y_train), dtype=torch.float32).unsqueeze(1)

X_val = torch.tensor(np.array(X_val), dtype=torch.float32)
y_val = torch.tensor(np.array(y_val), dtype=torch.float32).unsqueeze(1)

print("Training input:", X_train.shape)
print("Training output:", y_train.shape)
print("Validation input:", X_val.shape)
print("Validation output:", y_val.shape)

class StockRNN(nn.Module):

    def __init__(self):
        super().__init__()

        self.rnn = nn.RNN(
            input_size=5,
            hidden_size=50,
            num_layers=1,
            batch_first=True
        )

        self.fc = nn.Linear(50, 1)

    def forward(self, x):

        output, hidden = self.rnn(x)

        # Use the last time step
        output = output[:, -1, :]

        output = self.fc(output)

        return output


model = StockRNN().to(device)

criterion = nn.MSELoss()
optimizer = optim.Adam(model.parameters(), lr=0.001)

print(model)

train_dataset = TensorDataset(X_train, y_train)

train_loader = DataLoader(
    train_dataset,
    batch_size=32,
    shuffle=True
)

X_val = X_val.to(device)
y_val = y_val.to(device)

epochs = 10

train_losses = []
val_losses = []

start_time = time.time()

for epoch in range(epochs):

    model.train()
    total_train_loss = 0

    for X_batch, y_batch in train_loader:

        X_batch = X_batch.to(device)
        y_batch = y_batch.to(device)

        optimizer.zero_grad()

        outputs = model(X_batch)
        loss = criterion(outputs, y_batch)

        loss.backward()
        optimizer.step()

        total_train_loss += loss.item()

    avg_train_loss = total_train_loss / len(train_loader)

    # Validation
    model.eval()

    with torch.no_grad():
        val_outputs = model(X_val)
        val_loss = criterion(val_outputs, y_val).item()

    train_losses.append(avg_train_loss)
    val_losses.append(val_loss)

    print(
        f"Epoch [{epoch+1}/{epochs}] "
        f"Training Loss: {avg_train_loss:.6f} "
        f"Validation Loss: {val_loss:.6f}"
    )

training_time = time.time() - start_time

print("\nTraining time:", round(training_time, 2), "seconds")

model.eval()

with torch.no_grad():
    predictions = model(X_val).cpu().numpy()

actual = y_val.cpu().numpy()

# Reverse Min-Max scaling for closing price
close_index = 3

predicted_prices = (
    predictions * scaler.scale_[close_index]
    + scaler.min_[close_index]
)

actual_prices = (
    actual * scaler.scale_[close_index]
    + scaler.min_[close_index]
)

# Evaluation metrics
mae = mean_absolute_error(actual_prices, predicted_prices)

rmse = np.sqrt(
    mean_squared_error(actual_prices, predicted_prices)
)

print("\n========== MODEL PERFORMANCE ==========")
print("MAE:", round(mae, 2))
print("RMSE:", round(rmse, 2))
print("Training Time:", round(training_time, 2), "seconds")

plt.figure(figsize=(12, 5))

plt.plot(
    data.index[split_index:],
    actual_prices.flatten(),
    label="Actual Price"
)

plt.plot(
    data.index[split_index:],
    predicted_prices.flatten(),
    label="Predicted Price"
)

plt.title("Actual vs Predicted TCS Stock Prices")
plt.xlabel("Date")
plt.ylabel("Closing Price (INR)")
plt.legend()
plt.grid()
plt.show()


# Training and validation loss
plt.figure(figsize=(8, 4))

plt.plot(train_losses, label="Training Loss")
plt.plot(val_losses, label="Validation Loss")

plt.title("RNN Training and Validation Loss")
plt.xlabel("Epoch")
plt.ylabel("MSE Loss")
plt.legend()
plt.grid()
plt.show()

