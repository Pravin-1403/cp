import tensorflow as tf
import tensorflow_datasets as tfds
import numpy as np
import matplotlib.pyplot as plt

print("TensorFlow Version:", tf.__version__)

# --------------------------------------------------
# 1. LOAD DATASET
# --------------------------------------------------

print("Loading Oxford-IIIT Pet Dataset...")

(ds_train, ds_test), info = tfds.load(
    "oxford_iiit_pet",
    split=["train", "test"],
    with_info=True
)

print("Training samples:", info.splits["train"].num_examples)
print("Testing samples:", info.splits["test"].num_examples)

# --------------------------------------------------
# 2. PREPROCESS IMAGES AND MASKS
# --------------------------------------------------

IMG_SIZE = 128
BATCH_SIZE = 16
NUM_CLASSES = 3

def preprocess(data):

    image = tf.image.resize(
        data["image"],
        (IMG_SIZE, IMG_SIZE)
    )

    image = tf.cast(image, tf.float32) / 255.0

    mask = tf.image.resize(
        data["segmentation_mask"],
        (IMG_SIZE, IMG_SIZE),
        method="nearest"
    )

    mask = tf.cast(mask, tf.int32)

    # Oxford-IIIT Pet mask labels are 1, 2, 3.
    # Convert them to 0, 1, 2.
    mask = mask - 1

    return image, tf.squeeze(mask, axis=-1)

train_data = (
    ds_train
    .map(preprocess, num_parallel_calls=tf.data.AUTOTUNE)
    .batch(BATCH_SIZE)
    .prefetch(tf.data.AUTOTUNE)
)

test_data = (
    ds_test
    .map(preprocess, num_parallel_calls=tf.data.AUTOTUNE)
    .batch(BATCH_SIZE)
    .prefetch(tf.data.AUTOTUNE)
)

print("Dataset preprocessing completed!")

# --------------------------------------------------
# 3. BUILD U-NET MODEL
# --------------------------------------------------

def conv_block(x, filters):

    x = tf.keras.layers.Conv2D(
        filters, 3, padding="same", activation="relu"
    )(x)

    x = tf.keras.layers.BatchNormalization()(x)

    x = tf.keras.layers.Conv2D(
        filters, 3, padding="same", activation="relu"
    )(x)

    x = tf.keras.layers.BatchNormalization()(x)

    return x


def build_unet():

    inputs = tf.keras.Input(
        shape=(IMG_SIZE, IMG_SIZE, 3)
    )

    # Encoder
    c1 = conv_block(inputs, 32)
    p1 = tf.keras.layers.MaxPooling2D()(c1)

    c2 = conv_block(p1, 64)
    p2 = tf.keras.layers.MaxPooling2D()(c2)

    c3 = conv_block(p2, 128)
    p3 = tf.keras.layers.MaxPooling2D()(c3)

    # Bottleneck
    c4 = conv_block(p3, 256)

    # Decoder
    u1 = tf.keras.layers.UpSampling2D()(c4)
    u1 = tf.keras.layers.Concatenate()([u1, c3])
    c5 = conv_block(u1, 128)

    u2 = tf.keras.layers.UpSampling2D()(c5)
    u2 = tf.keras.layers.Concatenate()([u2, c2])
    c6 = conv_block(u2, 64)

    u3 = tf.keras.layers.UpSampling2D()(c6)
    u3 = tf.keras.layers.Concatenate()([u3, c1])
    c7 = conv_block(u3, 32)

    outputs = tf.keras.layers.Conv2D(
        NUM_CLASSES,
        1,
        activation="softmax"
    )(c7)

    return tf.keras.Model(inputs, outputs)


model = build_unet()

model.compile(
    optimizer="adam",
    loss="sparse_categorical_crossentropy",
    metrics=["accuracy"]
)

model.summary()

# --------------------------------------------------
# 4. TRAIN U-NET MODEL
# --------------------------------------------------

print("Training U-Net model...")

history = model.fit(
    train_data,
    epochs=5,
    validation_data=test_data
)

print("Training completed!")

# --------------------------------------------------
# 5. PLOT TRAINING ACCURACY AND LOSS
# --------------------------------------------------

plt.figure(figsize=(12, 4))

plt.subplot(1, 2, 1)
plt.plot(history.history["accuracy"], label="Training Accuracy")
plt.plot(history.history["val_accuracy"], label="Validation Accuracy")
plt.title("Model Accuracy")
plt.xlabel("Epoch")
plt.ylabel("Accuracy")
plt.legend()

plt.subplot(1, 2, 2)
plt.plot(history.history["loss"], label="Training Loss")
plt.plot(history.history["val_loss"], label="Validation Loss")
plt.title("Model Loss")
plt.xlabel("Epoch")
plt.ylabel("Loss")
plt.legend()

plt.tight_layout()
plt.show()

# --------------------------------------------------
# 6. VISUALIZE PREDICTED SEGMENTATION MASKS
# --------------------------------------------------

images, masks = next(iter(test_data))

predictions = model.predict(images[:5], verbose=0)

predicted_masks = np.argmax(
    predictions,
    axis=-1
)

plt.figure(figsize=(15, 12))

for i in range(5):

    plt.subplot(5, 3, i * 3 + 1)
    plt.imshow(images[i])
    plt.title("Original Image")
    plt.axis("off")

    plt.subplot(5, 3, i * 3 + 2)
    plt.imshow(masks[i], cmap="viridis", vmin=0, vmax=2)
    plt.title("Ground Truth Mask")
    plt.axis("off")

    plt.subplot(5, 3, i * 3 + 3)
    plt.imshow(predicted_masks[i], cmap="viridis", vmin=0, vmax=2)
    plt.title("Predicted Mask")
    plt.axis("off")

plt.tight_layout()
plt.show()

# --------------------------------------------------
# 7. EVALUATE IoU, DICE AND PIXEL ACCURACY
# --------------------------------------------------

confusion_matrix = tf.zeros(
    (NUM_CLASSES, NUM_CLASSES),
    dtype=tf.float32
)

for images, masks in test_data:

    predictions = model.predict(images, verbose=0)

    pred_masks = tf.argmax(
        predictions,
        axis=-1,
        output_type=tf.int32
    )

    actual_masks = tf.cast(masks, tf.int32)

    cm = tf.math.confusion_matrix(
        tf.reshape(actual_masks, [-1]),
        tf.reshape(pred_masks, [-1]),
        num_classes=NUM_CLASSES,
        dtype=tf.float32
    )

    confusion_matrix += cm

# Calculate metrics
intersection = tf.linalg.diag_part(confusion_matrix)

actual_pixels = tf.reduce_sum(
    confusion_matrix, axis=1
)

predicted_pixels = tf.reduce_sum(
    confusion_matrix, axis=0
)

union = actual_pixels + predicted_pixels - intersection

iou = intersection / (union + 1e-7)

dice = (
    2 * intersection
) / (
    actual_pixels + predicted_pixels + 1e-7
)

pixel_accuracy = (
    tf.reduce_sum(intersection)
    / (tf.reduce_sum(confusion_matrix) + 1e-7)
)

mean_iou = tf.reduce_mean(iou)
mean_dice = tf.reduce_mean(dice)

print("\n------ FINAL EVALUATION ------")

print("Mean IoU:", round(float(mean_iou), 4))
print("Mean Dice Coefficient:", round(float(mean_dice), 4))
print("Pixel Accuracy:", round(float(pixel_accuracy), 4))

print("\nPer-Class IoU:", iou.numpy())
print("Per-Class Dice:", dice.numpy())

print("\nPRACTICAL 9 COMPLETED SUCCESSFULLY!")

