# 1. IMPORT LIBRARIES

import numpy as np
import pandas as pd
import matplotlib.pyplot as plt
import tensorflow as tf
import time

from tensorflow.keras.datasets import fashion_mnist
from tensorflow.keras.models import Sequential
from tensorflow.keras.layers import (
    Input, Dense, Flatten, Dropout,
    BatchNormalization, LayerNormalization,
    RandomRotation, RandomFlip, ReLU
)
from tensorflow.keras.optimizers import Adam
from tensorflow.keras.regularizers import L1L2
from tensorflow.keras.callbacks import EarlyStopping

np.random.seed(42)
tf.random.set_seed(42)

# 2. LOAD FASHION-MNIST DATASET

(X_train, y_train), (X_test, y_test) = fashion_mnist.load_data()

print("Training Data:", X_train.shape)
print("Testing Data:", X_test.shape)

# 3. NORMALIZE DATA

X_train = X_train.astype("float32") / 255.0
X_test = X_test.astype("float32") / 255.0

# 4. SPLIT TRAINING AND VALIDATION DATA

X_train, X_val = X_train[:50000], X_train[50000:]
y_train, y_val = y_train[:50000], y_train[50000:]

print("Training Samples:", X_train.shape[0])
print("Validation Samples:", X_val.shape[0])
print("Testing Samples:", X_test.shape[0])

# 5. DISPLAY SAMPLE IMAGES

class_names = [
    'T-shirt/top', 'Trouser', 'Pullover', 'Dress', 'Coat',
    'Sandal', 'Shirt', 'Sneaker', 'Bag', 'Ankle boot'
]

plt.figure(figsize=(10, 5))

for i in range(10):
    plt.subplot(2, 5, i + 1)
    plt.imshow(X_train[i], cmap='gray')
    plt.title(class_names[y_train[i]])
    plt.axis('off')

plt.tight_layout()
plt.show()

# 6. DEFINE DATA AUGMENTATION

data_augmentation = Sequential([
    RandomRotation(0.05),
    RandomFlip("horizontal")
], name="data_augmentation")

# 7. DEFINE L1 AND L2 REGULARIZATION

regularizer = L1L2(
    l1=0.00001,
    l2=0.0001
)

# 8. BUILD DEEP MLP MODEL

def build_model(normalization):

    model = Sequential([
        Input(shape=(28, 28)),

        # Data Augmentation
        data_augmentation,

        # Flatten image
        Flatten(),

        # Hidden Layer 1
        Dense(512, kernel_regularizer=regularizer),

        # Normalization
        normalization(),

        ReLU(),
        Dropout(0.5),

        # Hidden Layer 2
        Dense(256, kernel_regularizer=regularizer),

        normalization(),

        ReLU(),
        Dropout(0.5),

        # Hidden Layer 3
        Dense(128, kernel_regularizer=regularizer),

        normalization(),

        ReLU(),
        Dropout(0.5),

        # Output Layer
        Dense(10, activation='softmax')
    ])

    model.compile(
        optimizer=Adam(learning_rate=0.001),
        loss='sparse_categorical_crossentropy',
        metrics=['accuracy']
    )

    return model

# 9. DEFINE EARLY STOPPING

early_stopping = EarlyStopping(
    monitor='val_loss',
    patience=5,
    restore_best_weights=True,
    verbose=1
)

# 10. TRAIN BATCH NORMALIZATION MODEL

print("\n========== BATCH NORMALIZATION ==========")

bn_model = build_model(BatchNormalization)

start_time = time.time()

bn_history = bn_model.fit(
    X_train,
    y_train,
    validation_data=(X_val, y_val),
    epochs=30,
    batch_size=128,
    callbacks=[early_stopping],
    verbose=1
)

bn_time = time.time() - start_time

# Evaluate Batch Normalization
bn_val_loss, bn_val_acc = bn_model.evaluate(
    X_val, y_val, verbose=0
)

bn_test_loss, bn_test_acc = bn_model.evaluate(
    X_test, y_test, verbose=0
)

print("\nBatch Normalization Results")
print("Validation Accuracy:", round(bn_val_acc * 100, 2), "%")
print("Test Accuracy:", round(bn_test_acc * 100, 2), "%")
print("Training Time:", round(bn_time, 2), "seconds")
print("Epochs Completed:", len(bn_history.history['loss']))

# 11. TRAIN LAYER NORMALIZATION MODEL

print("\n========== LAYER NORMALIZATION ==========")

ln_model = build_model(LayerNormalization)

start_time = time.time()

ln_history = ln_model.fit(
    X_train,
    y_train,
    validation_data=(X_val, y_val),
    epochs=30,
    batch_size=128,
    callbacks=[early_stopping],
    verbose=1
)

ln_time = time.time() - start_time

# Evaluate Layer Normalization
ln_val_loss, ln_val_acc = ln_model.evaluate(
    X_val, y_val, verbose=0
)

ln_test_loss, ln_test_acc = ln_model.evaluate(
    X_test, y_test, verbose=0
)

print("\nLayer Normalization Results")
print("Validation Accuracy:", round(ln_val_acc * 100, 2), "%")
print("Test Accuracy:", round(ln_test_acc * 100, 2), "%")
print("Training Time:", round(ln_time, 2), "seconds")
print("Epochs Completed:", len(ln_history.history['loss']))

# 12. COMPARE TRAINING LOSS

plt.figure(figsize=(10, 6))

plt.plot(
    bn_history.history['loss'],
    marker='o',
    label='Batch Normalization'
)

plt.plot(
    ln_history.history['loss'],
    marker='o',
    label='Layer Normalization'
)

plt.title("Training Loss Comparison")
plt.xlabel("Epochs")
plt.ylabel("Training Loss")
plt.legend()
plt.grid(True)
plt.show()

# 13. COMPARE VALIDATION LOSS

plt.figure(figsize=(10, 6))

plt.plot(
    bn_history.history['val_loss'],
    marker='o',
    label='Batch Normalization'
)

plt.plot(
    ln_history.history['val_loss'],
    marker='o',
    label='Layer Normalization'
)

plt.title("Validation Loss Comparison")
plt.xlabel("Epochs")
plt.ylabel("Validation Loss")
plt.legend()
plt.grid(True)
plt.show()

# 14. COMPARE VALIDATION ACCURACY

plt.figure(figsize=(10, 6))

plt.plot(
    bn_history.history['val_accuracy'],
    marker='o',
    label='Batch Normalization'
)

plt.plot(
    ln_history.history['val_accuracy'],
    marker='o',
    label='Layer Normalization'
)

plt.title("Validation Accuracy Comparison")
plt.xlabel("Epochs")
plt.ylabel("Validation Accuracy")
plt.legend()
plt.grid(True)
plt.show()

# 15. COMPARE TRAINING AND VALIDATION ACCURACY

plt.figure(figsize=(10, 6))

plt.plot(
    bn_history.history['accuracy'],
    label='BN Training Accuracy'
)

plt.plot(
    bn_history.history['val_accuracy'],
    label='BN Validation Accuracy'
)

plt.plot(
    ln_history.history['accuracy'],
    label='LN Training Accuracy'
)

plt.plot(
    ln_history.history['val_accuracy'],
    label='LN Validation Accuracy'
)

plt.title("Training vs Validation Accuracy")
plt.xlabel("Epochs")
plt.ylabel("Accuracy")
plt.legend()
plt.grid(True)
plt.show()

# 16. ACCURACY COMPARISON BAR GRAPH

models = ['Batch Normalization', 'Layer Normalization']

val_accuracies = [
    bn_val_acc * 100,
    ln_val_acc * 100
]

plt.figure(figsize=(8, 5))

plt.bar(models, val_accuracies)

plt.title("Validation Accuracy Comparison")
plt.xlabel("Normalization Technique")
plt.ylabel("Accuracy (%)")
plt.ylim(0, 100)
plt.grid(axis='y')
plt.show()

# 17. TRAINING TIME COMPARISON

training_times = [bn_time, ln_time]

plt.figure(figsize=(8, 5))

plt.bar(models, training_times)

plt.title("Training Time Comparison")
plt.xlabel("Normalization Technique")
plt.ylabel("Time (seconds)")
plt.grid(axis='y')
plt.show()

# 18. GENERALIZATION GAP

bn_gap = (bn_history.history['accuracy'][-1] -
          bn_history.history['val_accuracy'][-1]) * 100

ln_gap = (ln_history.history['accuracy'][-1] -
          ln_history.history['val_accuracy'][-1]) * 100

# 19. FINAL COMPARISON TABLE

comparison = pd.DataFrame({
    'Normalization': models,

    'Validation Accuracy (%)': [
        round(bn_val_acc * 100, 2),
        round(ln_val_acc * 100, 2)
    ],

    'Test Accuracy (%)': [
        round(bn_test_acc * 100, 2),
        round(ln_test_acc * 100, 2)
    ],

    'Training Loss': [
        round(bn_history.history['loss'][-1], 4),
        round(ln_history.history['loss'][-1], 4)
    ],

    'Training Time (sec)': [
        round(bn_time, 2),
        round(ln_time, 2)
    ],

    'Epochs Completed': [
        len(bn_history.history['loss']),
        len(ln_history.history['loss'])
    ],

    'Generalization Gap (%)': [
        round(bn_gap, 2),
        round(ln_gap, 2)
    ]
})

print("\n========== FINAL COMPARISON ==========")
print(comparison.to_string(index=False))

# 20. FINAL CONCLUSION

print("\n========== CONCLUSION ==========")

if bn_val_acc > ln_val_acc:
    print("Batch Normalization achieved higher validation accuracy.")
elif ln_val_acc > bn_val_acc:
    print("Layer Normalization achieved higher validation accuracy.")
else:
    print("Both normalization techniques achieved equal validation accuracy.")

print("\nBatch Normalization:")
print("Normalizes activations using batch statistics.")

print("\nLayer Normalization:")
print("Normalizes activations independently for each sample.")

print("\nRegularization techniques used:")
print("1. Dropout (0.5)")
print("2. L1 Regularization")
print("3. L2 Regularization")
print("4. Early Stopping (patience=5)")
print("5. Data Augmentation (Rotation and Horizontal Flip)")

print("\nExperiment completed successfully!")

