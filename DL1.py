# Load MNIST dataset
(X_train, y_train), (X_test, y_test) = mnist.load_data()

# Select 10,000 training and 2,000 testing images
X_train = X_train[:10000]
y_train = y_train[:10000]

X_test = X_test[:2000]
y_test = y_test[:2000]

print("Training data shape:", X_train.shape)
print("Testing data shape:", X_test.shape)

# Normalize pixel values between 0 and 1
X_train = X_train.astype("float32") / 255.0
X_test = X_test.astype("float32") / 255.0

# Flatten 28x28 images into 784 features
X_train_flat = X_train.reshape(10000, 784)
X_test_flat = X_test.reshape(2000, 784)

print("Flattened training shape:", X_train_flat.shape)
print("Flattened testing shape:", X_test_flat.shape)

plt.figure(figsize=(10, 4))

for i in range(10):
    plt.subplot(2, 5, i + 1)
    plt.imshow(X_train[i], cmap="gray")
    plt.title(f"Label: {y_train[i]}")
    plt.axis("off")

plt.tight_layout()
plt.show()

# Build MLP model
model = Sequential([
    Input(shape=(784,)),

    Dense(128, activation='relu'),
    Dense(128, activation='relu'),
    Dense(128, activation='relu'),

    Dense(10, activation='softmax')
])

# Compile model
model.compile(
    optimizer=Adam(learning_rate=0.001),
    loss='sparse_categorical_crossentropy',
    metrics=['accuracy']
)

# Display model architecture
model.summary()

# Start training timer
start_time = time.time()

# Train model
history = model.fit(
    X_train_flat,
    y_train,
    epochs=3,
    batch_size=128,
    validation_data=(X_test_flat, y_test),
    verbose=1
)

# Calculate training time
mlp_time = time.time() - start_time

print("MLP Training Time:", round(mlp_time, 2), "seconds")

# Evaluate model
test_loss, test_accuracy = model.evaluate(
    X_test_flat,
    y_test,
    verbose=0
)

print("MLP Test Accuracy:", round(test_accuracy * 100, 2), "%")
print("MLP Test Loss:", round(test_loss, 4))

plt.figure(figsize=(8, 5))

plt.plot(history.history['loss'], marker='o',
         label='Training Loss')

plt.plot(history.history['val_loss'], marker='o',
         label='Validation Loss')

plt.title('MLP Training and Validation Loss')
plt.xlabel('Epochs')
plt.ylabel('Loss')
plt.legend()
plt.grid(True)
plt.show()

# Create Logistic Regression model
lr_model = LogisticRegression(
    max_iter=1000,
    solver='lbfgs'
)

# Training time
start_time = time.time()

lr_model.fit(X_train_flat, y_train)

lr_time = time.time() - start_time

# Prediction
lr_predictions = lr_model.predict(X_test_flat)

# Accuracy
lr_accuracy = accuracy_score(y_test, lr_predictions)

print("Logistic Regression Accuracy:",
      round(lr_accuracy * 100, 2), "%")

print("Logistic Regression Training Time:",
      round(lr_time, 2), "seconds")

# Create Decision Tree model
dt_model = DecisionTreeClassifier(
    criterion='gini',
    max_depth=20,
    random_state=42
)

# Training time
start_time = time.time()

dt_model.fit(X_train_flat, y_train)

dt_time = time.time() - start_time

# Prediction
dt_predictions = dt_model.predict(X_test_flat)

# Accuracy
dt_accuracy = accuracy_score(y_test, dt_predictions)

print("Decision Tree Accuracy:",
      round(dt_accuracy * 100, 2), "%")

print("Decision Tree Training Time:",
      round(dt_time, 2), "seconds")

# Store model results
models = ['MLP', 'Logistic Regression', 'Decision Tree']

accuracies = [
    test_accuracy * 100,
    lr_accuracy * 100,
    dt_accuracy * 100
]

training_times = [
    mlp_time,
    lr_time,
    dt_time
]

# Display comparison table
print("\nMODEL COMPARISON")
print("-" * 60)
print(f"{'Model':<25} {'Accuracy (%)':<15} {'Time (sec)':<15}")
print("-" * 60)

for i in range(3):
    print(f"{models[i]:<25} {accuracies[i]:<15.2f} "
          f"{training_times[i]:<15.2f}")

print("-" * 60)

plt.figure(figsize=(8, 5))

plt.bar(models, accuracies)

plt.title('Accuracy Comparison of ML Models')
plt.xlabel('Models')
plt.ylabel('Accuracy (%)')
plt.ylim(0, 100)

plt.xticks(rotation=15)
plt.grid(axis='y')

plt.show()

plt.figure(figsize=(8, 5))

plt.bar(models, training_times)

plt.title('Training Time Comparison')
plt.xlabel('Models')
plt.ylabel('Training Time (seconds)')

plt.xticks(rotation=15)
plt.grid(axis='y')

plt.show()

# Get MLP predictions
mlp_predictions = np.argmax(
    model.predict(X_test_flat, verbose=0),
    axis=1
)

print("MLP Classification Report:")
print(classification_report(y_test, mlp_predictions))

