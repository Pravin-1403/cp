import torch
import torch.nn as nn
import torch.optim as optim
import torch.nn.functional as F
import torchvision
import torchvision.transforms as transforms
import matplotlib.pyplot as plt
import time

from torch.utils.data import DataLoader, Subset

# Device
device = torch.device("cuda" if torch.cuda.is_available() else "cpu")
print("Device:", device)

# Transform
transform = transforms.ToTensor()

# Load CIFAR-10
train_data = torchvision.datasets.CIFAR10(
    root="./data", train=True,
    download=True, transform=transform
)

test_data = torchvision.datasets.CIFAR10(
    root="./data", train=False,
    download=True, transform=transform
)

# Select small subsets for fast execution
train_data = Subset(train_data, range(2000))
test_data = Subset(test_data, range(500))

train_loader = DataLoader(
    train_data, batch_size=128, shuffle=True
)

test_loader = DataLoader(
    test_data, batch_size=128, shuffle=False
)

print("Training images:", len(train_data))
print("Testing images:", len(test_data))

class CNN(nn.Module):

    def __init__(self, kernel, stride, padding, pool):
        super().__init__()

        pad = kernel // 2 if padding == "same" else 0

        Pool = (
            nn.MaxPool2d if pool == "max"
            else nn.AvgPool2d
        )

        self.conv1 = nn.Conv2d(
            3, 32, kernel_size=kernel,
            stride=stride, padding=pad
        )

        self.conv2 = nn.Conv2d(
            32, 64, kernel_size=kernel,
            stride=1, padding=pad
        )

        self.pool = Pool(2)

        self.adaptive = nn.AdaptiveAvgPool2d((2, 2))

        self.fc = nn.Sequential(
            nn.Flatten(),
            nn.Linear(64 * 2 * 2, 128),
            nn.ReLU(),
            nn.Linear(128, 10)
        )

    def forward(self, x):

        x = F.relu(self.conv1(x))
        x = self.pool(x)

        x = F.relu(self.conv2(x))
        x = self.pool(x)

        x = self.adaptive(x)

        return self.fc(x)

# CNN configurations
configs = [
    (3, 1, "same", "max"),
    (5, 1, "same", "max"),
    (3, 2, "same", "max"),
    (3, 1, "valid", "max"),
    (3, 1, "same", "average")
]

results = {}

for kernel, stride, padding, pool in configs:

    name = f"K{kernel}_S{stride}_{padding}_{pool}"

    print("\nTraining:", name)

    model = CNN(kernel, stride, padding, pool).to(device)

    criterion = nn.CrossEntropyLoss()
    optimizer = optim.Adam(model.parameters(), lr=0.001)

    losses = []
    start = time.time()

    # Training
    model.train()

    total_loss = 0

    for images, labels in train_loader:

        images = images.to(device)
        labels = labels.to(device)

        outputs = model(images)
        loss = criterion(outputs, labels)

        optimizer.zero_grad()
        loss.backward()
        optimizer.step()

        total_loss += loss.item()

    avg_loss = total_loss / len(train_loader)
    losses.append(avg_loss)

    # Testing
    model.eval()

    correct = 0
    total = 0

    with torch.no_grad():

        for images, labels in test_loader:

            images = images.to(device)
            labels = labels.to(device)

            outputs = model(images)
            predicted = outputs.argmax(dim=1)

            total += labels.size(0)
            correct += (predicted == labels).sum().item()

    accuracy = 100 * correct / total
    elapsed = time.time() - start

    results[name] = {
        "loss": avg_loss,
        "accuracy": accuracy,
        "time": elapsed
    }

    print("Training Loss:", round(avg_loss, 4))
    print("Test Accuracy:", round(accuracy, 2), "%")
    print("Time:", round(elapsed, 2), "seconds")

# 1. Training loss comparison
names = list(results.keys())
losses = [results[n]["loss"] for n in names]

plt.figure(figsize=(9, 5))
plt.bar(names, losses)
plt.xlabel("CNN Configurations")
plt.ylabel("Training Loss")
plt.title("Training Loss Comparison")
plt.xticks(rotation=30)
plt.tight_layout()
plt.show()


# 2. Accuracy comparison
accuracies = [results[n]["accuracy"] for n in names]

plt.figure(figsize=(9, 5))
plt.bar(names, accuracies)
plt.xlabel("CNN Configurations")
plt.ylabel("Test Accuracy (%)")
plt.title("CNN Accuracy Comparison")
plt.xticks(rotation=30)
plt.tight_layout()
plt.show()


# 3. Visualize convolution filters
filters = model.conv1.weight.detach().cpu()

plt.figure(figsize=(8, 5))

for i in range(16):
    plt.subplot(4, 4, i + 1)
    plt.imshow(filters[i].permute(1, 2, 0).numpy())
    plt.axis("off")

plt.suptitle("Convolution Filters")
plt.show()


# 4. Visualize feature maps
model.eval()

images, labels = next(iter(test_loader))
sample = images[0:1].to(device)

with torch.no_grad():
    feature_maps = F.relu(model.conv1(sample))

feature_maps = feature_maps[0].cpu()

plt.figure(figsize=(8, 5))

for i in range(16):
    plt.subplot(4, 4, i + 1)
    plt.imshow(feature_maps[i], cmap="viridis")
    plt.axis("off")

plt.suptitle("CNN Feature Maps")
plt.show()


# 5. Final comparison
print("\n===== FINAL CNN COMPARISON =====")

for name, result in results.items():

    print("\nConfiguration:", name)
    print("Training Loss:", round(result["loss"], 4))
    print("Test Accuracy:", round(result["accuracy"], 2), "%")
    print("Training Time:", round(result["time"], 2), "seconds")

