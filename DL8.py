def evaluate_yolo():
    metric = MeanAveragePrecision(iou_type="bbox")

    total_time = 0
    count = 0

    for i in range(num_images):
        image, annotation = test_data[i]
        target = get_target(annotation)

        if len(target["boxes"]) == 0:
            continue

        # Convert tensor image to NumPy image
        img = (image.permute(1, 2, 0).numpy() * 255).astype(np.uint8)

        start = time.time()

        result = yolo_model.predict(
            img,
            conf=0.30,
            verbose=False,
            device=0 if torch.cuda.is_available() else "cpu"
        )[0]

        if torch.cuda.is_available():
            torch.cuda.synchronize()

        total_time += time.time() - start
        count += 1

        boxes, labels, scores = [], [], []

        for box, cls, score in zip(
            result.boxes.xyxy.cpu(),
            result.boxes.cls.cpu(),
            result.boxes.conf.cpu()
        ):
            name = yolo_model.names[int(cls)]
            name = aliases.get(name, name)

            if name in class_to_id:
                boxes.append(box)
                labels.append(class_to_id[name])
                scores.append(score)

        pred = {
            "boxes": torch.stack(boxes) if boxes else torch.empty((0, 4)),
            "labels": torch.tensor(labels, dtype=torch.int64),
            "scores": torch.tensor(scores)
        }

        metric.update(
            [pred],
            [{
                "boxes": target["boxes"],
                "labels": target["labels"]
            }]
        )

    result = metric.compute()

    map_value = result["map"].item()
    fps = count / total_time if total_time > 0 else 0

    return map_value, fps


print("Evaluating YOLOv8...")
yolo_map, yolo_fps = evaluate_yolo()

print("YOLOv8 mAP:", round(yolo_map, 4))
print("YOLOv8 FPS:", round(yolo_fps, 2))

