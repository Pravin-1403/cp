# Map COCO class names to Pascal VOC names
aliases = {
    "airplane": "aeroplane",
    "motorcycle": "motorbike",
    "dining table": "diningtable",
    "potted plant": "pottedplant",
    "couch": "sofa",
    "tv": "tvmonitor"
}

def convert_predictions(prediction, model_names):
    boxes = prediction["boxes"].detach().cpu()
    labels = prediction["labels"].detach().cpu()
    scores = prediction["scores"].detach().cpu()

    new_boxes, new_labels, new_scores = [], [], []

    for box, label, score in zip(boxes, labels, scores):
        if score < 0.30:
            continue

        name = model_names[int(label)]
        name = aliases.get(name, name)

        if name in class_to_id:
            new_boxes.append(box)
            new_labels.append(class_to_id[name])
            new_scores.append(score)

    return {
        "boxes": torch.stack(new_boxes) if new_boxes else torch.empty((0, 4)),
        "labels": torch.tensor(new_labels, dtype=torch.int64),
        "scores": torch.tensor(new_scores)
    }


def evaluate_torch_model(model, model_names):
    metric = MeanAveragePrecision(iou_type="bbox")
    total_time = 0
    count = 0

    for i in range(num_images):
        image, annotation = test_data[i]
        target = get_target(annotation)

        if len(target["boxes"]) == 0:
            continue

        start = time.time()

        with torch.no_grad():
            prediction = model([image.to(device)])[0]

        if device.type == "cuda":
            torch.cuda.synchronize()

        total_time += time.time() - start
        count += 1

        pred = convert_predictions(prediction, model_names)

        metric.update(
            [pred],
            [{
                "boxes": target["boxes"],
                "labels": target["labels"]
            }]
        )

    result = metric.compute()

    map_value = result["map"].item()
    fps = count / total_time if total_time > 0 else 0

    return map_value, fps


